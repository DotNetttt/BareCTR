import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const blocks = JSON.parse(fs.readFileSync(path.join(here, 'data/blocks-1.21.8.json')));
const legacy = JSON.parse(fs.readFileSync(path.join(here, 'data/legacy.json'))).blocks;
const registry = fs.readFileSync(path.join(here, '../source/registries.h'), 'utf8');
const internal = Object.fromEntries([...registry.matchAll(/^#define B_(\w+) (\d+)/gm)].map(m => [m[1], Number(m[2])]));
const aliases = {grass_path:'dirt_path', grass:'short_grass', sign:'oak_sign', wall_sign:'oak_wall_sign', stone_slab:'smooth_stone_slab'};
export function stateFor(name, props = {}) {
  name = aliases[name] ?? name;
  const b = blocks.find(b => b.name === name);
  if (!b) throw Error(`Unknown modern block ${name}`);
  let defaults = b.defaultState - b.minStateId;
  const indices = [];
  for (let i = b.states.length - 1; i >= 0; i--) { indices[i] = defaults % b.states[i].num_values; defaults = Math.floor(defaults / b.states[i].num_values); }
  let offset = 0;
  for (const [i, s] of b.states.entries()) {
    const values = s.type === 'bool' ? ['true','false'] : s.values ?? Array.from({length:s.num_values}, (_,j)=>String(j));
    const index = props[s.name] === undefined ? indices[i] : values.indexOf(String(props[s.name]));
    if (index < 0) throw Error(`Invalid ${name}.${s.name}=${props[s.name]}`);
    offset = offset * s.num_values + index;
  }
  return b.minStateId + offset;
}
const states = [], physics = [];
for (let id = 0; id < 256; id++) for (let meta = 0; meta < 16; meta++) {
  let value = legacy[`${id}:${meta}`] ?? legacy[`${id}:0`];
  if ((id === 50 || id === 75 || id === 76) && meta === 0) value = legacy[`${id}:5`];
  if (!value) { states.push(stateFor('barrier')); physics.push(internal.barrier); continue; }
  const [, rawName, properties] = value.match(/^minecraft:([^[]+)(?:\[(.*)\])?$/);
  const name = aliases[rawName] ?? rawName;
  const props = Object.fromEntries((properties ?? '').split(',').filter(Boolean).map(p=>p.split('=')));
  if (name.endsWith('_wall')) for (const side of ['east','north','south','west']) if (props[side]) props[side] = props[side] === 'true' ? 'low' : 'none';
  if (name.endsWith('_leaves')) props.persistent = 'true';
  states.push(stateFor(name, props));
  let fallback = name.replace('wall_torch','torch').replace('wall_sign','sign');
  if (!(fallback in internal)) {
    if (name.includes('slab')) fallback = 'stone_slab';
    else if (name.includes('stairs')) fallback = 'cobblestone_stairs';
    else if (name.includes('leaves')) fallback = 'oak_leaves';
    else if (name.includes('log') || name.includes('wood')) fallback = 'oak_log';
    else fallback = blocks.find(b=>b.name===name)?.boundingBox === 'empty' ? 'air' : 'stone';
  }
  if (id === 8 || id === 9) fallback = meta && meta < 8 ? `water_${meta}` : 'water';
  if (id === 10 || id === 11) fallback = 'lava';
  physics.push(internal[fallback]);
}
const array = (type, name, data) => `static const ${type} ${name}[4096] = {\n${Array.from({length:256},(_,i)=>'  '+data.slice(i*16,i*16+16).join(', ')+',').join('\n')}\n};\n`;
fs.writeFileSync(path.join(here, '../source/legacy_blocks.h'), '// Generated by tools/generate-legacy.mjs from PrismarineJS minecraft-data.\n#ifndef LEGACY_BLOCKS_H\n#define LEGACY_BLOCKS_H\n#include <stdint.h>\n' + array('uint16_t','legacy_states',states) + array('uint8_t','legacy_physics',physics) + '#endif\n');
console.log('Generated 4096 legacy block states and physics mappings.');


